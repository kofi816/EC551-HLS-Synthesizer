"""
EC551 HLS Synthesizer
Directed Acyclic Graph (DAG) Construction
"""

import argparse
import json

try:
    from .parser import parse_file
    from .ssa import convert_to_ssa
except ImportError:
    from parser import parse_file
    from ssa import convert_to_ssa


def build_dag(ssa_equations: list[dict[str, str]]) -> dict[str, dict]:
    """
    Construct a dependency DAG from SSA equations.

    Each node represents an arithmetic operation.

    Node structure:
        {
            "operator": "+", "-", or "*",
            "operands": [operand1, operand2],
            "dependencies": [preceding operations]
        }

    Primary inputs are not represented as operation nodes.
    """

    # Collect all SSA result variables.
    results = [equation["result"] for equation in ssa_equations]

    # Ensure SSA assignments have unique destination names.
    if len(results) != len(set(results)):
        raise ValueError("SSA result names must be unique")

    produced = set(results)

    dag = {}

    # Construct operation nodes.
    for equation in ssa_equations:

        result = equation["result"]
        operator = equation["operator"]

        operands = [
            equation["operand1"],
            equation["operand2"]
        ]

        # Dependencies are operands generated by other operations.
        dependencies = list(dict.fromkeys(
            operand
            for operand in operands
            if operand in produced
        ))

        dag[result] = {
            "operator": operator,
            "operands": operands,
            "dependencies": dependencies
        }

    # Validate that dependencies are computed before they are used.
    completed = set()

    for result, node in dag.items():

        for dependency in node["dependencies"]:

            if dependency not in completed:
                raise ValueError(
                    f"Invalid SSA dependency: {result} uses "
                    f"{dependency} before it is computed"
                )

        completed.add(result)

    return dag


def get_primary_inputs(dag: dict[str, dict]) -> list[str]:
    """
    Identify primary inputs that are not generated by operations.
    """

    results = set(dag)

    primary_inputs = list(dict.fromkeys(
        operand
        for node in dag.values()
        for operand in node["operands"]
        if operand not in results
    ))

    return primary_inputs


def main():

    cli = argparse.ArgumentParser(
        description="Build an EC551 HLS dependency DAG"
    )

    cli.add_argument(
        "input_file",
        help="Path to input equations text file"
    )

    cli.add_argument(
        "--export-dag",
        metavar="OUTPUT_FILE",
        help="Export DAG as JSON"
    )

    args = cli.parse_args()

    # Step 1: Parse equations.
    equations = parse_file(args.input_file)

    # Step 2: Convert to SSA.
    ssa_equations = convert_to_ssa(equations)

    # Step 3: Construct the DAG.
    dag = build_dag(ssa_equations)

    # Step 4: Display the DAG.
    print(json.dumps(dag, indent=2))

    # Step 5: Display primary inputs.
    print("Primary inputs:", ", ".join(get_primary_inputs(dag)))

    # Step 6: Export if requested.
    if args.export_dag:

        with open(args.export_dag, "w", encoding="utf-8") as file:
            json.dump(dag, file, indent=2)
            file.write("\n")

        print(f"DAG exported to {args.export_dag}")


if __name__ == "__main__":
    main()