import argparse
import json
import sys
from pathlib import Path

# Support both direct script execution and module imports.
if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from hls.parser import parse_file
from hls.ssa import convert_to_ssa
from hls.dag import build_dag


def asap_schedule(dag, latencies=None):
    """
    Schedule DAG operations as soon as their dependencies are available.

    Parameters
    ----------
    dag : dict
        Dependency graph generated by dag.py.

    latencies : dict, optional
        Number of clock cycles required by each operation.
        Defaults to one cycle for +, -, and *.

    Returns
    -------
    dict
        Maps operation IDs to their earliest starting clock cycle.

        Example:
        {
            "X_1": 0,
            "Y_1": 1,
            "Z_1": 1,
            "Q_1": 2
        }
    """

    if latencies is None:
        latencies = {
            "+": 1,
            "-": 1,
            "*": 1
        }

    # Validate operation latencies.
    for operator, latency in latencies.items():

        if type(latency) is not int or latency < 1:
            raise ValueError(
                f"Latency for {operator} must be a positive integer"
            )

    schedule = {}

    # Track operations currently being evaluated to detect cycles.
    visiting = set()

    def earliest_start(operation):
        """
        Determine the earliest cycle an operation can begin.
        """

        # Return an already computed start cycle.
        if operation in schedule:
            return schedule[operation]

        # Detect cyclic dependencies.
        if operation in visiting:
            raise ValueError(
                f"Cycle detected involving {operation}"
            )

        # Check that the operation exists.
        if operation not in dag:
            raise ValueError(
                f"Unknown operation dependency: {operation}"
            )

        visiting.add(operation)

        node = dag[operation]
        operator = node["operator"]

        # Check that a latency is defined.
        if operator not in latencies:
            raise ValueError(
                f"Missing latency for operator {operator}"
            )

        # Independent operations can start at cycle 0.
        start = 0

        # Determine when all dependencies are available.
        for dependency in node["dependencies"]:

            if dependency not in dag:
                raise ValueError(
                    f"Unknown operation dependency: {dependency}"
                )

            # Earliest start of the preceding operation.
            producer_start = earliest_start(dependency)

            # Latency of the preceding operation.
            producer_operator = dag[dependency]["operator"]
            producer_latency = latencies[producer_operator]

            # Wait until the preceding operation completes.
            start = max(
                start,
                producer_start + producer_latency
            )

        visiting.remove(operation)

        # Store the operation's start cycle.
        schedule[operation] = start

        return start

    # Schedule all operations.
    for operation in dag:
        earliest_start(operation)

    # Preserve the DAG operation order.
    return {
        operation: schedule[operation]
        for operation in dag
    }


def main():
    """
    Run the complete HLS frontend and ASAP scheduling pipeline.
    """

    parser = argparse.ArgumentParser(
        description="EC551 Unconstrained ASAP Scheduler"
    )

    parser.add_argument(
        "input_file",
        help="Input equations text file"
    )

    parser.add_argument(
        "--dag-json",
        action="store_true",
        help="Load an existing DAG JSON file instead of building the DAG"
    )

    args = parser.parse_args()

    if args.dag_json:

        # Option 1: Load an existing DAG JSON file.
        with open(args.input_file, "r", encoding="utf-8") as file:
            dag = json.load(file)

    else:

        # Option 2: Automatically build the DAG from equations.

        # Step 1: Parse the input equations.
        equations = parse_file(args.input_file)

        # Step 2: Convert equations to SSA.
        ssa_equations = convert_to_ssa(equations)

        # Step 3: Construct the dependency DAG.
        dag = build_dag(ssa_equations)

    # Step 4: Perform ASAP scheduling.
    schedule = asap_schedule(dag)

    # Step 5: Display the schedule.
    print(json.dumps(schedule, indent=2))


if __name__ == "__main__":
    main()